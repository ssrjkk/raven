def test_the_landing_text_tokens_clear_the_contrast_floor() -> None:
    """Measured from the ``:root`` block, not from a screenshot: every text colour against every
    surface colour it can sit on, at the WCAG AA floor for body text."""
    contrast = load_module("design_contrast", ROOT / "tests" / "test_design_contracts.py").contrast
    root = css_rule(":root")
    token = dict(re.findall(r"\s(--[a-z0-9-]+): ([^;]+);", root))
    text_tokens = ("--ink", "--ink-mute", "--violet-text", "--violet-bright", "--fuchsia")
    surfaces = ("--bg", "--bg-panel", "--bg-card")
    measured = {
        f"{fg} on {bg}": round(contrast(token[fg], token[bg]), 2)
        for fg in text_tokens
        for bg in surfaces
        if token[fg].startswith("#")
    }
    assert len(measured) == 15, measured
    failing = {pair: value for pair, value in measured.items() if value < 4.5}
    assert failing == {}, failing


