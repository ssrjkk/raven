def test_scroll_linked_motion_is_stopped_by_reduced_motion() -> None:
    """A scroll-driven animation is timed by the timeline, not by a duration, so the blanket
    ``animation-duration: 0.001ms`` that quiets everything else leaves it running. Every selector
    the ``@supports`` block gives a timeline has to be switched off by name — otherwise the stage
    stays at ``opacity: 0`` for a visitor who asked for no motion."""
    driven = {
        selector
        for selectors, body in rules_in(at_block("@supports (animation-timeline: view())"))
        if "animation-timeline" in body
        for selector in selectors
    }
    assert driven, "the @supports block stopped declaring a scroll-driven reveal"
    stopped: set[str] = set()
    for selectors, body in rules_in(at_block("@media (prefers-reduced-motion: reduce)")):
        if "animation-name: none" in body:
            assert "opacity: 1" in body, selectors
            stopped |= selectors
    assert driven <= stopped, sorted(driven - stopped)


