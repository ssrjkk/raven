"""Landing page invariant: what site/index.html claims must match the code.

``site/tools-data.js`` and ``site/mcp-frames.js`` are generated by
``scripts/record_site_frames.py`` from a live ``raven-mcp`` process, while the page also
hand-writes counts (tool count, version, hero preview, adapter count) and embeds request
frames in its preset buttons. These tests compare those statements with the generated data
and with the tool registry itself, so a renamed tool, a version bump, an unrecorded button
or a stray file in ``site/`` fails CI instead of shipping a wrong claim.

The last group pins how the site is published instead: MkDocs must not build into ``site/``,
exactly one workflow may hand a tree to GitHub Pages, that workflow installs a pinned theme,
the documentation loads no font from a third-party host, and the MkDocs palette is the
repository's purple-black brand (not Material's default indigo). The first two were violated
at once when the docs workflow uploaded ``site`` after ``mkdocs build`` had overwritten it,
and the live root served documentation with every landing asset 404.

The narrow-viewport guard checks a chain that spans three files: the toggle button, the
panel rules in the ``max-width: 900px`` query and the handler in ``main.js``. Half of it
looking finished is what left the last nav link scrolled out of sight behind a hidden
scrollbar on a phone.
"""

