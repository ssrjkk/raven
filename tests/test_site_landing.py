def at_block(prelude: str) -> str:
    """The ``{...}`` body of the first at-rule whose prelude is ``prelude``, braces counted."""
    css = read(STYLES)
    open_brace = css.index("{", css.index(prelude))
    depth = 0
    for index in range(open_brace, len(css)):
        if css[index] == "{":
            depth += 1
        elif css[index] == "}":
            depth -= 1
            if depth == 0:
                return css[open_brace : index + 1]
    raise AssertionError(f"unbalanced braces after {prelude!r}")


def rules_in(block: str) -> list[tuple[set[str], str]]:
    """Selectors and declaration body of every rule sitting directly inside an at-rule block."""
    body = re.sub(r"/\*.*?\*/", "", block, flags=re.S)
    return [
        ({" ".join(part.split()) for part in head.split(",")}, declarations)
        for head, declarations in re.findall(r"([^{}]+)\{([^{}]*)\}", body)
    ]


