def test_documentation_carries_the_brand_palette() -> None:
    """Material's public build resolves only its own named colors in ``theme.palette`` — a hex
    is written to the page as a data attribute with no matching rule, and the theme falls back
    to its default indigo. The brand scheme is overridden by a stylesheet instead, and that
    stylesheet has to be listed at the top level: an ``extra_css`` key inside ``theme:`` reaches
    only a legacy template global the theme ignores, which copied the file into the build
    without any page ever linking it.

    The palette values are read from the landing page's ``:root`` block so the two surfaces
    cannot drift apart."""
    config = mkdocs_config()
    assert "extra_css" not in config["theme"]
    sheets = config["extra_css"]
    assert sheets == ["stylesheets/brand.css"]
    css = read(ROOT / "docs" / sheets[0])
    assert f"--md-primary-fg-color: {brand_token('bg')};" in css
    assert f"--md-typeset-a-color: {brand_token('violet-deep')};" in css


