"""Site invariants: every page's claims, the pages' agreement, and how they are published.

``site/tools-data.js`` and ``site/mcp-frames.js`` are generated by
``scripts/record_site_frames.py`` from a live ``raven-mcp`` process, while the pages also
hand-write counts (tool count, version, hero preview, adapter count) and embed request frames
in the preset buttons. These tests compare those statements with the generated data and with
the tool registry itself, so a renamed tool, a version bump, an unrecorded button or a stray
file in ``site/`` fails CI instead of shipping a wrong claim.

The site is six content pages plus a 404, and the split has invariants of its own: every page
carries the same nav and footer, exactly one link marks itself current, the sitemap lists the
content pages and not the 404, each block of markup belongs to exactly one page, and the
landing page still maps every other page. Content drifting back onto the landing page is how
the registry grid once shipped twice.

The deploy group pins publishing instead: MkDocs must build strict into ``build/docs`` with
the session archive excluded, exactly one workflow may hand a tree to GitHub Pages, that
workflow installs a pinned theme, the documentation loads no font from a third-party host,
and the audit guarding the built tree can fail — it returns non-zero when MkDocs wrote nothing
and when any page or stylesheet requests another host.

The narrow-viewport guard checks a chain that spans three files: the toggle button, the panel
rules in the ``max-width: 900px`` query and the handler in ``main.js``. Half of it looking
finished is what left the last nav link scrolled out of sight behind a hidden scrollbar on a
phone, and the page-aware split means the chain has to hold on every page, not only on the
landing page.
"""

