def mkdocs_config() -> dict[str, Any]:
    return cast("dict[str, Any]", yaml.safe_load(read(MKDOCS_YML)))


def nav_leaves(node: Any) -> list[str]:
    if isinstance(node, dict):
        return [text for key, value in node.items() for text in [str(key), *nav_leaves(value)]]
    if isinstance(node, list):
        return [text for item in node for text in nav_leaves(item)]
    return [str(node)]


def pages_upload_paths() -> set[tuple[str, str]]:
    """``(workflow, artifact path)`` for every job that hands a tree to GitHub Pages."""
    uploads: set[tuple[str, str]] = set()
    for workflow in sorted(WORKFLOWS.glob("*.yml")):
        for job in (yaml.safe_load(read(workflow)) or {}).get("jobs", {}).values():
            for step in job.get("steps") or []:
                if str(step.get("uses", "")).startswith("actions/upload-pages-artifact"):
                    uploads.add((workflow.name, step["with"]["path"]))
    return uploads


