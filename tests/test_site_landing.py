def test_page_loads_no_third_party_asset() -> None:
    """Typography is self-hosted: every ``link``/``script`` request stays first-party.

    A third-party stylesheet would also hand the visitor's IP to another host, which a
    page advertising a self-hosted server should not do.
    """
    for path in (INDEX, SITE / "404.html"):
        for url in external_asset_urls(path):
            assert url.startswith(FIRST_PARTY), f"{path.name} loads {url}"
        assert "fonts.googleapis.com" not in read(path)
        assert "fonts.gstatic.com" not in read(path)


def test_faces_point_at_fonts_that_ship() -> None:
    css = read(STYLES)
    faces = re.findall(r"@font-face \{(.*?)\}", css, re.S)
    assert len(faces) >= 5
    for face in faces:
        family = re.search(r"font-family: '([^']+)'", face)
        src = re.search(r"url\('([^']+)'\)", face)
        assert family is not None and src is not None, face
        assert (SITE / src.group(1)).is_file(), src.group(1)
        assert "font-display: swap" in face
    used = {m.group(1) for f in faces if (m := re.search(r"font-family: '([^']+)'", f))}
    assert used == {"IBM Plex Mono", "IBM Plex Sans", "Space Grotesk"}


def media(width: int) -> str:
    """One ``@media (max-width: <width>px)`` block, up to its column-zero closing brace."""
    css = read(STYLES)
    block = css[css.index(f"@media (max-width: {width}px) {{") :]
    return block[: block.index("\n}") + 2]


def test_narrow_viewports_get_a_disclosure_menu() -> None:
    """Below 900px eight links do not fit beside the brand. Kept on one line they scrolled,
    and because the scrollbar is suppressed the last link left no trace that anything was
    there; wrapped, they stacked rows of links over the hero. The button, the panel and the
    handler are three files that have to name each other, so pin the whole chain."""
    html = read(INDEX)
    toggle = NAV_TOGGLE.search(html)
    assert toggle is not None
    assert f'<nav aria-label="Primary" id="{toggle.group(1)}">' in html

    mobile = media(900)
    assert ".js .nav-toggle {" in mobile
    assert ".js .navbar.nav-open > nav {" in mobile
    assert ".nav-links" not in media(560)

    js = read(MAIN_JS)
    for hook in ("nav-open", "aria-expanded", "matchMedia"):
        assert hook in js, hook


def css_rule(selector: str) -> str:
    """Body of one top-level rule, written as ``<selector> {`...`}`` in the stylesheet."""
    css = read(STYLES)
    start = css.index(f"\n{selector} {{")
    return css[start : css.index("\n}", start) + 2]


