"""Generate the brand icons the installable app ships, from the one drawing of the mark.

``site/favicon.svg`` is that drawing. The console's tab icon used to be an emoji chick inlined as a
``data:`` URI, the manifest asked Android for a raster and answered itself with two SVGs, the offline
shell named no icon at all, and ``web/public/icons`` restated the mark's path data by hand at 192 and
512 units -- so the product wore the brand on the landing and a different face everywhere the browser,
the home screen or the taskbar drew it. Every file here is copied from the vector, re-vectorised from
it, or rendered from it, which means editing the mark reaches all of them.

Used by ``scripts/setup.sh`` and ``scripts/setup.ps1`` after the web build.

Usage:
    python scripts/make_web_icons.py            # write every icon
    python scripts/make_web_icons.py --check    # fail if a shipped icon is not the current mark
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path

from icon_render import MARK_SVG, canvas_size, plate, render_icon

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "web" / "public"
ICONS = PUBLIC / "icons"
FAVICON_SVG = PUBLIC / "favicon.svg"
FAVICON_ICO = PUBLIC / "favicon.ico"

#: Vector tiles the manifest links, each the mark drawn at that side.
VECTOR_TILES = {192: ICONS / "icon-192.svg", 512: ICONS / "icon-512.svg"}

#: Rasters the same slot also has to be able to fill: Android installs and notification art.
RASTER_TILES = {192: ICONS / "icon-192.png", 512: ICONS / "icon-512.png"}

#: Frames of the Windows favicon, which is what a browser asks for when SVG icons are unavailable.
ICO_FRAMES = [(16, 16), (24, 24), (32, 32), (48, 48)]

GENERATED = "<!-- generated by scripts/make_web_icons.py from site/favicon.svg, do not edit -->"

_SVG_HEAD = re.compile(r"<svg\b[^>]*>")
_SVG_BODY = re.compile(r"<svg\b[^>]*>(.*)</svg>", re.S)
_RECT_TAG = re.compile(r"<rect\b[^>]*>")
_VIEW_BOX = re.compile(r'viewBox="[^"]*"')
_TILE_SIDE = re.compile(r'\b(width|height)="[^"]+"')
_CORNER = re.compile(r'\brx="[^"]+"')


def _number(value: float) -> str:
    """A coordinate as text, without float noise: `icon_render` reads these numbers back."""
    text = f"{value:.4f}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text or "0"


def tile(size: int) -> str:
    """The mark as a vector of its own at ``size`` units.

    A tile is the shipped document scaled, not a re-telling of it: the path data, the plate's colour and the
    mark's own group come out of ``site/favicon.svg`` unchanged, and only the document's units, the plate's
    side and its corner radius are set to the size asked for. A copy therefore differs from the mark by the
    size it is drawn at and by nothing else -- which is what lets the parity guard compare one drawing with
    another exactly, instead of allowing for a coordinate this script re-typeset and rounded.
    """
    source = MARK_SVG.read_text(encoding="utf-8")
    drawing_match, head_tag, plate_rect = _SVG_BODY.search(source), _SVG_HEAD.search(source), _RECT_TAG.search(source)
    if drawing_match is None or head_tag is None or plate_rect is None:
        msg = f"{MARK_SVG} is not one svg document carrying a background tile"
        raise ValueError(msg)
    drawing = drawing_match.group(1)
    if len(_RECT_TAG.findall(drawing)) != 1:
        msg = "the brand mark must carry exactly one background tile to scale a plate from"
        raise ValueError(msg)

    scale = size / canvas_size()
    _background, radius = plate()
    # The plate's own line goes empty when its tag is removed, and a blank line in a generated file reads
    # as a hand edit that the next run will not reproduce.
    body = "\n".join(line for line in _RECT_TAG.sub("", drawing, count=1).splitlines() if line.strip())
    rect = _TILE_SIDE.sub(lambda match: f'{match.group(1)}="{size}"', plate_rect.group(0))
    rect = _CORNER.sub(f'rx="{_number(radius * scale)}"', rect)
    head_text = _VIEW_BOX.sub(f'viewBox="0 0 {size} {size}"', head_tag.group(0))
    lines = [
        GENERATED,
        head_text,
        f"  {rect}",
        f'  <g transform="scale({_number(scale)})">',
        textwrap.indent(body, "    "),
        "  </g>",
        "</svg>",
    ]
    return "\n".join(lines) + "\n"


def write_icons() -> list[Path]:
    """Write every icon the bundle ships; returns the paths written."""
    written: list[Path] = []
    ICONS.mkdir(parents=True, exist_ok=True)
    # Written every run: skipping an existing file is how the shipped icons kept the old bird.
    FAVICON_SVG.write_bytes(MARK_SVG.read_bytes())
    written.append(FAVICON_SVG)
    for size, path in VECTOR_TILES.items():
        path.write_text(tile(size), encoding="utf-8", newline="\n")
        written.append(path)
    for size, path in RASTER_TILES.items():
        render_icon(size).save(path, format="PNG")
        written.append(path)
    render_icon(max(size for size, _ in ICO_FRAMES)).save(FAVICON_ICO, format="ICO", sizes=ICO_FRAMES)
    written.append(FAVICON_ICO)
    return written


def drift() -> list[str]:
    """Shipped icons that are not what the current mark produces."""
    from PIL import Image

    stale: list[str] = []
    if not FAVICON_SVG.is_file() or FAVICON_SVG.read_bytes() != MARK_SVG.read_bytes():
        stale.append(FAVICON_SVG.name)
    for size, path in VECTOR_TILES.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != tile(size):
            stale.append(path.name)
    for size, path in RASTER_TILES.items():
        painted = render_icon(size).convert("RGBA")
        if not path.is_file() or Image.open(path).convert("RGBA").tobytes() != painted.tobytes():
            stale.append(path.name)
    largest = max(size for size, _ in ICO_FRAMES)
    if not FAVICON_ICO.is_file():
        stale.append(FAVICON_ICO.name)
    else:
        # Opening an ICO hands over its largest frame, which is what a reader asking for no size receives,
        # so the file is stale when it holds a largest frame that is not the current render.
        handle = Image.open(FAVICON_ICO)
        if (
            handle.size != (largest, largest)
            or handle.convert("RGBA").tobytes() != render_icon(largest).convert("RGBA").tobytes()
        ):
            stale.append(FAVICON_ICO.name)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the app's brand icons from site/favicon.svg")
    parser.add_argument("--check", action="store_true", help="Fail if a shipped icon is out of date")
    args = parser.parse_args()

    if args.check:
        stale = drift()
        if stale:
            print(f"{', '.join(stale)} out of date -- run python scripts/make_web_icons.py", file=sys.stderr)
            return 1
        print("every icon in web/public is the current mark")
        return 0

    for path in write_icons():
        print(f"icon written: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
