"""Emit the payload `/api/health` answers, so the SPA is tested against the server's contract.

Measured on a live gateway on 2026-11-18: the dashboard crashed into its error boundary
(`TypeError: p.checks.map is not a function`) because `HealthRegistry.check_all()` answers `checks` as a
mapping of name to result, while `web/src/api/types.ts` declared an array of `{name, ok, latency_ms,
critical}` and `web/e2e/dashboard.spec.ts` stubbed that invented array -- so every spec passed and the shipped
page never rendered. A hand-typed stub cannot fail that way, which is why this file generates the payload out
of the route the gateway serves and types it with `HealthData`: the emitted literal stops compiling if the
SPA's declaration and the server's answer disagree again.

Usage:
    python scripts/gen_health_fixture.py --write
    python scripts/gen_health_fixture.py           # compare, exit non-zero on drift
"""

from __future__ import annotations

import argparse
import asyncio
import json
import pathlib
import shutil
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from raven.core.gateway.health_monitor import HealthMonitor
from raven.core.status_api import create_status_router

REPO = pathlib.Path(__file__).resolve().parents[1]
TARGET = REPO / "web" / "e2e" / "fixtures" / "health.ts"

FROZEN_TIMESTAMP = 1_700_000_000.0
"""`check_all()` stamps its answer with `time.time()`, and a byte-for-byte gate cannot follow a clock."""


async def _available() -> bool:
    return True


async def _unavailable() -> bool:
    msg = "no route to host"
    raise OSError(msg)


def payload(*, failing: tuple[str, ...] = ()) -> dict[str, object]:
    """The answer of the route a running gateway serves, with the checks production registers.

    `HealthRegistry.register()` replaces the entry, so its `cache_ttl` starts cold on every call and the
    emission does not depend on how long this process has been alive. A failing check goes through the
    registry's own except path, which is where `detail` comes from.

    The gateway is the real object, not a stand-in: `create_status_router` takes one because `/api/status`
    reads its channels and registry, and handing it an empty namespace to reach the health route would
    leave the fixture one refactor away from answering an invented payload. It is built the way
    `gen_api_fixtures.py` builds it, on a scratch database the operator's tree never sees.
    """
    return asyncio.run(_payload(failing=failing))


async def _payload(*, failing: tuple[str, ...]) -> dict[str, object]:
    import tempfile
    from pathlib import Path

    import httpx
    from fastapi import FastAPI

    from raven.channels.webchat.channel import WebChatChannel
    from raven.core.db import Database
    from raven.core.gateway.gateway import Gateway
    from raven.core.plugin_loader import PluginLoader

    scratch = Path(tempfile.mkdtemp(prefix="raven-gen-health-fixture-"))
    try:
        db = Database(scratch / "raven.db")
        await db.connect()
        loader = PluginLoader()
        gateway = Gateway(db, loader)
        await gateway.register_channel(WebChatChannel(db))

        HealthMonitor(
            db_check=_unavailable if "database" in failing else _available,
            llm_check=_unavailable if "llm" in failing else _available,
        ).register_checks()

        app = FastAPI()
        app.include_router(create_status_router(gateway, loader, asyncio.Event()))
        transport = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(transport=transport, base_url="http://gen") as client:
            answer = (await client.get("/api/health")).json()
        await gateway.stop()
        await db.disconnect()
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    if not isinstance(answer, dict):
        raise TypeError(f"GET /api/health answered {type(answer).__name__}, not an object")
    answer["timestamp"] = FROZEN_TIMESTAMP
    return answer


def render() -> str:
    variants = {"healthOk": payload(), "healthDegraded": payload(failing=("llm",))}
    consts = "\n\n".join(
        f"export const {name}: HealthData = {json.dumps(body, indent=2, sort_keys=True)};"
        for name, body in variants.items()
    )
    return (
        "/* Generated by scripts/gen_health_fixture.py from the answer of GET /api/health -- do not edit by hand.\n"
        "   Regenerate with: python scripts/gen_health_fixture.py --write */\n"
        "\n"
        'import type { HealthData } from "../../src/api/types";\n'
        "\n"
        f"{consts}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET}")
        return 0
    if not TARGET.is_file():
        print(f"{TARGET} is missing — run python scripts/gen_health_fixture.py --write")
        return 1
    if TARGET.read_text(encoding="utf-8") != text:
        print(f"{TARGET} no longer matches what /api/health answers; regenerate it")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
