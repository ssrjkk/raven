"""Render the design token files into a static CSS custom-property sheet.

ThemeContext injects the same variables inline on <html>, but only after React mounts — every paint
before that (the HTML shell, the first committed frame) had nothing to resolve against and fell back
to literals scattered through the stylesheets. Those literals could only ever describe one theme, so
they were wrong for two of three, and wrong in the direction of a colour flash or an invisible
control. This sheet makes the first paint truthful; the inline injection still overrides it, because
inline styles beat any rule on the same element.

    python scripts/gen_theme_css.py            # rewrite web/src/styles/themes.css
    python scripts/gen_theme_css.py --check    # fail if the sheet is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

WEB = Path(__file__).resolve().parent.parent / "web"
DESIGN = WEB / "src" / "design"
OUTPUT = WEB / "src" / "styles" / "themes.css"
OUTPUT_TAILWIND = WEB / "src" / "styles" / "tailwind-theme.css"

THEMES: tuple[tuple[str, str], ...] = (
    ("tokens.json", ':root,\n[data-theme="dark"]'),
    ("tokens.light.json", '[data-theme="light"]'),
    ("tokens.midnight.json", '[data-theme="midnight"]'),
)

_META_KEYS = frozenset({"$schema", "description", "version"})

SENTINEL_START = "/* design-tokens:start - generated by scripts/gen_theme_css.py --print-surface, do not edit */"
SENTINEL_END = "/* design-tokens:end */"

ROOT = Path(__file__).resolve().parent.parent
FONTS_CSS = WEB / "src" / "styles" / "fonts.css"
FONTS_SRC = WEB / "public" / "fonts"
SITE_FONTS = ROOT / "site" / "fonts"
EXTENSION_FONTS = ROOT / "extension" / "src" / "popup" / "fonts"
VSCODE_FONTS = ROOT / "extension" / "vscode" / "assets" / "fonts"

#: How each offline surface reaches a file that `web/public/fonts` holds. `gateway` is an absolute path
#: from the origin, so it only resolves while the built SPA is mounted; `extension` is relative to
#: `src/popup/index.html`, the only document in the package, because an extension has no origin;
#: `vscode` is the placeholder the panel interpolates with `webview.asWebviewUri` -- the only address a
#: webview may read, and the reason those faces have to be copied into the extension's own assets.
FONT_PREFIXES: dict[str, str] = {"gateway": "/fonts/", "extension": "fonts/", "vscode": "${fontRoot}/"}

#: The families an offline surface can name: the first entry of the two stacks it embeds. Space Grotesk
#: is absent because SURFACE_TOKENS carries no display token, and it is also the one vendored file with
#: no Cyrillic -- a page that set body text in it would render Russian in the system font.
FONT_STACK_TOKENS = ("--dt-typography-font-family-sans", "--dt-typography-font-family-mono")

_FACE_BLOCK = re.compile(r"@font-face\s*\{[^}]*\}")
_FACE_FAMILY = re.compile(r"font-family:\s*'([^']+)'")
_FACE_URL = re.compile(r"url\('(/fonts/[^']+)'\)")

#: The dark tokens the offline surfaces embed, in declaration order.
#:
#: One block for every surface that cannot import `themes.css`, rather than one per document: the gate
#: compares each copy with what this prints, and identical text is what makes a pasted region verifiable.
#: What belongs here is measured, not remembered -- a gate takes the union of the `var(--dt-*)` names the
#: host documents actually reference, so a token nothing paints with is reported the same way an alias
#: no rule reads is.
SURFACE_TOKENS = (
    "--dt-colors-bg-primary",
    "--dt-colors-bg-secondary",
    "--dt-colors-border-default",
    "--dt-colors-border-focus",
    "--dt-colors-accent-default",
    "--dt-colors-accent-hover",
    "--dt-colors-accent-active",
    "--dt-colors-accent-muted",
    "--dt-colors-accent-subtle",
    "--dt-colors-brand-secondary",
    "--dt-colors-surface-card",
    "--dt-colors-surface-elevated",
    "--dt-colors-surface-inset-highlight",
    "--dt-colors-text-primary",
    "--dt-colors-text-secondary",
    "--dt-colors-text-link",
    "--dt-colors-text-on-accent",
    "--dt-colors-status-success",
    "--dt-colors-status-warning",
    "--dt-colors-status-error",
    "--dt-colors-status-success-bg",
    "--dt-colors-status-warning-bg",
    "--dt-colors-status-error-bg",
    "--dt-typography-font-family-sans",
    "--dt-typography-font-family-mono",
    "--dt-typography-font-size-caption",
    "--dt-typography-font-size-xs",
    "--dt-typography-font-size-sm",
    "--dt-typography-font-size-base",
    "--dt-typography-line-height-normal",
    "--dt-animation-duration-fast",
    "--dt-animation-duration-normal",
    "--dt-animation-easing-out",
    "--dt-shadow-glow-accent",
    "--dt-border-radius-sm",
    "--dt-border-radius-md",
    "--dt-border-radius-lg",
    "--dt-border-radius-xl",
)


def token_lines(data: dict[str, Any]) -> list[tuple[str, str]]:
    """Flatten a token tree into ``--dt-`` declarations in file order."""
    out: list[tuple[str, str]] = []

    def walk(node: Any, prefix: list[str]) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                walk(value, [*prefix, key])
        elif prefix and prefix[0] not in _META_KEYS:
            out.append(("--dt-" + "-".join(prefix), str(node)))

    for group, values in data.items():
        if group in _META_KEYS:
            continue
        walk(values, [group])
    return out


def render() -> str:
    blocks: list[str] = [
        "/* Generated by scripts/gen_theme_css.py from web/src/design/tokens.*.json — do not edit by hand.",
        " * This is the pre-hydration paint. ThemeContext writes the same properties inline on <html>",
        " * once it mounts, and those inline values win, so user-chosen accents and live theme",
        " * switching are unaffected. Keep the token files as the only thing you edit.",
        " */",
        "",
    ]
    for name, selector in THEMES:
        data = json.loads((DESIGN / name).read_text(encoding="utf-8"))
        lines = token_lines(data)
        body = "\n".join(f"  {prop}: {value};" for prop, value in lines)
        blocks.append(f"/* {name} — {len(lines)} tokens */")
        blocks.append(f"{selector} {{\n{body}\n}}\n")
    return "\n".join(blocks)


def render_tailwind() -> str:
    """The same tokens handed to Tailwind, so its utilities cannot be a second scale.

    213 components ask for `rounded-lg`/`rounded-xl`, which Tailwind resolves from its own default
    theme, not from `border-radius` in tokens.json: a utility and a token could then paint two
    different corners on the same card, and the landing's ladder (4px controls, 6px panels, 8px
    raised cards, 12px feature cards) reached the app only where a component opted into a token.
    Naming every step here is what makes the utility classes and the token layer say one number.
    """
    data = json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))
    values = dict(token_lines(data))
    radius = {
        key[len("--dt-border-radius-") :]: value
        for key, value in values.items()
        if key.startswith("--dt-border-radius-")
    }
    family = {
        key[len("--dt-typography-font-family-") :]: value
        for key, value in values.items()
        if key.startswith("--dt-typography-font-family-")
    }
    size = {
        key[len("--dt-typography-font-size-") :]: value
        for key, value in values.items()
        if key.startswith("--dt-typography-font-size-")
    }
    easing = {
        key[len("--dt-animation-easing-") :]: value
        for key, value in values.items()
        if key.startswith("--dt-animation-easing-")
    }
    widest = radius.get("xl", "12px")
    lines = [
        "/* Generated by scripts/gen_theme_css.py from web/src/design/tokens.json -- do not edit by hand.",
        " * Tailwind's default theme is a second set of numbers: components ask for `rounded-lg` and",
        " * get the library's 8px whether or not the product decided that. Import this after",
        ' * `@import "tailwindcss"` and the utilities resolve against the token files instead. Nothing',
        " * in the product is rounder than the landing's biggest card, so 2xl/3xl stop at `xl`.",
        " */",
        "@theme {",
        f"  --radius-xs: {radius.get('sm', '4px')};",
        f"  --radius-sm: {radius.get('sm', '4px')};",
        f"  --radius-md: {radius.get('md', '6px')};",
        f"  --radius-lg: {radius.get('lg', '8px')};",
        f"  --radius-xl: {widest};",
        f"  --radius-2xl: {widest};",
        f"  --radius-3xl: {widest};",
        f"  --font-sans: {family.get('sans', 'ui-sans-serif')};",
        f"  --font-mono: {family.get('mono', 'ui-monospace')};",
        f"  --font-display: {family.get('display', family.get('sans', 'ui-sans-serif'))};",
        *(f"  --text-{name}: {value};" for name, value in size.items()),
        f"  --ease-out: {easing.get('out', 'linear')};",
        f"  --ease-in-out: {easing.get('default', 'linear')};",
        f"  --ease-in: {easing.get('in', 'linear')};",
        "}",
        "",
    ]
    return "\n".join(lines)


def _face_rules() -> list[tuple[str, str, str]]:
    """Every face the SPA ships, as (family, file name, the rule with its `src:` line untouched).

    `web/src/styles/fonts.css` is the source of truth for the brand type because it is the sheet the
    product itself loads: it knows which families are variable, which subsets exist and which weights
    are discrete. The offline surfaces cannot be told about a face by hand without drifting from it --
    the webchat page and the MV3 popup each led their stacks with `"IBM Plex Sans"` while shipping no
    `@font-face` at all, so the brand rendered as system-ui everywhere the bundle was not loaded.
    """
    css = FONTS_CSS.read_text(encoding="utf-8")
    rules: list[tuple[str, str, str]] = []
    for block in _FACE_BLOCK.findall(css):
        family = _FACE_FAMILY.search(block)
        url = _FACE_URL.search(block)
        if not family or not url:
            raise AssertionError(f"fonts.css has an @font-face with no family or no src: {block[:60]}...")
        if not url.group(1).startswith("/fonts/"):
            raise AssertionError(f"fonts.css asks for {url.group(1)!r}, outside the vendored /fonts/ tree")
        name = url.group(1)[len("/fonts/") :]
        data = (FONTS_SRC / name).read_bytes()
        if data[:4] != b"wOF2":
            raise AssertionError(f"web/public/fonts/{name} is not a woff2 file")
        rules.append((family.group(1), name, block))
    if not rules:
        raise AssertionError("web/src/styles/fonts.css declares no @font-face: the brand has no type to deliver")
    return rules


def _surface_families() -> list[str]:
    """The families the offline surfaces lead their stacks with, read back out of the tokens."""
    values = dict(token_lines(json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))))
    lead: list[str] = []
    for token in FONT_STACK_TOKENS:
        stack = values[token]
        family = stack.split(",")[0].strip().strip("\"'")
        if family not in lead:
            lead.append(family)
    return lead


def font_files(target: str) -> list[str]:
    """The vendored file names a target ships: the surfaces the brand paints with, plus the display
    face for the precache, which the bundle uses and the offline surfaces do not."""
    if target == "precache":
        return sorted(name for _, name, _ in _face_rules())
    wanted = {family.lower() for family in _surface_families()}
    seen: list[str] = []
    for family, name, _ in _face_rules():
        if family.lower() in wanted and name not in seen:
            seen.append(name)
    missing = wanted - {family.lower() for family, _, _ in _face_rules()}
    if missing:
        raise AssertionError(f"tokens lead with {sorted(missing)} and fonts.css declares no face for them")
    if not seen:
        raise AssertionError(f"no face in fonts.css matches the surface families {sorted(wanted)}")
    return seen


def font_block(target: str) -> str:
    """The `@font-face` region a surface embeds, with that surface's own URL prefix.

    Four documents need the same eight faces and none of them can reach `fonts.css`: the gateway's
    webchat page and the offline shell are served from an origin, so they take `/fonts/`; the MV3
    popup is a file inside a package with no origin, so its copies travel beside the sheet as `fonts/`;
    and the VS Code webview reaches a file only through a URI the extension host prints, so its region
    carries the `${fontRoot}` placeholder the panel interpolates. A face region copied by hand is a
    face region that quietly stops matching the bundle, so this prints it and a test compares the
    result with what each document holds.
    """
    prefix = FONT_PREFIXES[target]
    shipped = set(font_files(target))
    body = "\n".join(
        block.replace(f"/fonts/{name}", f"{prefix}{name}") for _, name, block in _face_rules() if name in shipped
    )
    start, end = _font_sentinels(target)
    return f"{start}\n{body}\n{end}"


def precache_block() -> str:
    """The install-time cache list for the service worker, as JavaScript.

    The worker precached four documents and no fonts, so an offline launch asked the cache for a woff2,
    missed, and handed the request to `offline.html` -- an HTML body where a font was expected. The list
    is generated from the same sheet so a face added for the app is a face available offline.
    """
    entries = ",\n".join(f'  "{FONT_PREFIXES["gateway"]}{name}"' for name in font_files("precache"))
    start, end = _font_sentinels("precache")
    return f"{start}\nconst PRECACHE_FONTS = [\n{entries},\n];\n{end}"


def _font_sentinels(target: str) -> tuple[str, str]:
    return (
        f"/* brand-fonts:start - generated by scripts/gen_theme_css.py --print-fonts {target}, do not edit */",
        "/* brand-fonts:end */",
    )


#: The documents that hold a pasted copy of a printed face region, keyed by the command that prints it.
#: Same reason as `REGION_HOSTS` for the palette: a fifth surface that copies the faces by hand looks
#: right on the day it is written and stops matching `fonts.css` the moment someone adds a subset there.
FONT_REGION_HOSTS: dict[str, tuple[str, ...]] = {
    "--print-fonts gateway": ("raven/channels/webchat/channel.py", "web/public/offline.html"),
    "--print-fonts extension": ("extension/src/popup/popup.css",),
    "--print-fonts vscode": ("extension/vscode/src/panel.ts",),
    "--print-fonts precache": ("web/public/sw.js",),
}

#: Where each package surface keeps its own copies of the vendored bytes. A package is a zip with no
#: origin and no dev server, so `web/public/fonts` is not reachable from inside it.
FONT_PACKAGE_DIRS: dict[str, Path] = {"extension": EXTENSION_FONTS, "vscode": VSCODE_FONTS}


def font_region(command: str) -> str:
    """What a `--print-fonts` command prints right now, so a host list can be checked against the
    command it was produced by rather than a target re-typed next to the registration."""
    target = command.rsplit(" ", 1)[-1]
    return precache_block() if target == "precache" else font_block(target)


def sync_package_fonts() -> list[str]:
    """Copy the faces each package paints with out of `web/public/fonts`, and drop the ones it no longer asks for.

    Byte-for-byte copies, not a second download: two builds of the same Google Fonts subset differ by a
    header byte (the landing's mono files did until they were unified), and a reader cannot tell that
    apart from a different typeface -- they can only see that the app's `0` and the storefront's `0`
    stopped matching.
    """
    written: list[str] = []
    for target, dest in FONT_PACKAGE_DIRS.items():
        dest.mkdir(parents=True, exist_ok=True)
        wanted = set(font_files(target))
        for name in sorted(wanted):
            path = dest / name
            data = (FONTS_SRC / name).read_bytes()
            if not path.is_file() or path.read_bytes() != data:
                path.write_bytes(data)
                written.append(str(path.relative_to(ROOT)))
        for stale in sorted(dest.glob("*.woff2")):
            if stale.name not in wanted:
                stale.unlink()
                written.append(f"-{stale.relative_to(ROOT)}")
    return written


def _surface_sentinels(command: str) -> tuple[str, str]:
    """The markers a token region sits between, with the command that printed it named in the copy.

    `--print-surface` keeps the wording the shipped documents already hold, so regenerating one of them
    does not rewrite a line for nothing.
    """
    if command == "--print-surface":
        return SENTINEL_START, SENTINEL_END
    return SENTINEL_START.replace("--print-surface", command), SENTINEL_END


def scaffold_block() -> str:
    """The tokens a generated starter embeds: the surface scale with the two font stacks left out.

    A scaffold is a list of text files handed back over HTTP, so it carries no woff2 -- and a document
    that names `"IBM Plex Sans"` without shipping the file renders the brand as system-ui and looks
    correct in every screenshot, which is the defect the face-delivery guard exists to catch. Colour,
    geometry and the type ladder still arrive; the starter leads its stacks with the same system tail
    the brand falls through to, so what it promises is what a reader gets.
    """
    values = dict(token_lines(json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))))
    names = tuple(name for name in SURFACE_TOKENS if "font-family" not in name)
    missing = [name for name in names if name not in values]
    if missing:
        raise AssertionError(f"tokens.json publishes none of {missing}")
    body = "\n".join(f"  {name}: {values[name]};" for name in names)
    start, end = _surface_sentinels("--print-scaffold")
    return f"{start}\n{body}\n{end}"


def surface_block() -> str:
    """The dark tokens the two offline surfaces need, as one generated region.

    `raven/channels/webchat` and `extension/src/popup` are documents that never load the SPA bundle,
    so they cannot import themes.css. Left to hand-copy colours they drift into private palettes --
    the webchat page invented #8b5cf6 as its button surface and put white on it at 4.23:1. The region
    between the sentinels below is regenerated, and a gate compares it, so those surfaces keep one
    source of truth without needing a runtime file read.
    """
    values = dict(token_lines(json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))))
    missing = [name for name in SURFACE_TOKENS if name not in values]
    if missing:
        raise AssertionError(f"tokens.json publishes none of {missing}")
    body = "\n".join(f"  {name}: {values[name]};" for name in SURFACE_TOKENS)
    start, end = _surface_sentinels("--print-surface")
    return f"{start}\n{body}\n{end}"


#: The documents that hold a pasted copy of a generated region, keyed by the command that prints it.
REGION_HOSTS: dict[str, tuple[str, ...]] = {
    "--print-surface": (
        "extension/src/popup/popup.css",
        "extension/vscode/src/panel.ts",
        "raven/channels/webchat/channel.py",
        "web/public/offline.html",
    ),
    "--print-scaffold": ("raven/core/scaffold_api.py",),
}


def _region_inner(block: str, start: str, end: str) -> str:
    """The declarations a printed region carries between its own sentinels."""
    assert block.startswith(start) and block.endswith(end), f"{block[:40]!r} is not a delimited region"
    return block[len(start) : len(block) - len(end)]


def _pasted_regions() -> list[tuple[str, tuple[str, ...], str, str, str]]:
    """Each registered region as (what it is called, its hosts, its two markers, what the generator prints).

    The palette and the faces are pasted for the same reason -- an offline document cannot import the
    sheet -- so they are regenerated, compared and swept by one pair of loops rather than two.
    """
    out: list[tuple[str, tuple[str, ...], str, str, str]] = []
    for command, hosts in REGION_HOSTS.items():
        start, end = _surface_sentinels(command)
        out.append((command, hosts, start, end, surface_block() if command == "--print-surface" else scaffold_block()))
    for command, hosts in FONT_REGION_HOSTS.items():
        start, end = _font_sentinels(command.rsplit(" ", 1)[-1])
        out.append((command, hosts, start, end, font_region(command)))
    return out


def region_drift() -> list[str]:
    """Each pasted copy of a region, compared with what this script prints now.

    A sentinel that says `do not edit` next to a hand-typed block is an invitation to drift: the copy
    keeps the palette the day it was pasted while `tokens.json` moves on. This makes the paste a build
    product; a gate compares the same blocks and additionally sweeps the source tree for a document that
    pastes a region this registration does not cover.
    """
    offenders: list[str] = []
    for command, hosts, start, end, block in _pasted_regions():
        for rel in hosts:
            path = ROOT / rel
            if not path.is_file():
                offenders.append(f"{rel} is registered as a region host and does not exist")
                continue
            text = path.read_text(encoding="utf-8")
            if text.count(start) != 1:
                offenders.append(f"{rel} holds {text.count(start)} copies of the {command} region, expected 1")
                continue
            head, _, tail = text.partition(start)
            _, marker, after = tail.partition(end)
            if not marker:
                offenders.append(f"{rel} opens a {command} region it never closes")
                continue
            if head + start + _region_inner(block, start, end) + end + after != text:
                offenders.append(f"{rel} embeds a {command} region that is not what the generator prints")
    return offenders


def sync_surface_regions() -> list[str]:
    """Rewrite every pasted region with the generated one, and name the files that changed."""
    written: list[str] = []
    for command, hosts, start, end, block in _pasted_regions():
        for rel in hosts:
            path = ROOT / rel
            text = path.read_text(encoding="utf-8")
            if text.count(start) != 1:
                msg = f"{rel} holds {text.count(start)} copies of the {command} region; refusing to guess"
                raise AssertionError(msg)
            head, _, tail = text.partition(start)
            _, marker, after = tail.partition(end)
            if not marker:
                msg = f"{rel} opens a {command} region it never closes"
                raise AssertionError(msg)
            fresh = head + start + _region_inner(block, start, end) + end + after
            if fresh != text:
                path.write_text(fresh, encoding="utf-8", newline="\n")
                written.append(rel)
    return written


def mirrored_font_drift() -> list[str]:
    """Files that exist twice under the same name with different bytes.

    `site/fonts` is the storefront's copy of the same vendored type, and the two package trees are the
    copies that travel inside a zip. All of them drift by hand: the storefront's mono subsets were a
    separate Google Fonts download, and a second build of one subset is a different file that is
    supposed to look the same.
    """
    offenders: list[str] = []
    for mirror in (SITE_FONTS, *FONT_PACKAGE_DIRS.values()):
        for path in sorted(mirror.glob("*.woff2")) if mirror.is_dir() else []:
            source = FONTS_SRC / path.name
            if not source.is_file():
                offenders.append(f"{path.relative_to(ROOT)} has no counterpart in web/public/fonts")
            elif path.read_bytes() != source.read_bytes():
                offenders.append(f"{path.relative_to(ROOT)} is not the bytes web/public/fonts/{path.name} has")
    return offenders


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the sheet is up to date")
    parser.add_argument(
        "--print-surface", action="store_true", help="print the generated region the offline surfaces embed"
    )
    parser.add_argument("--print-scaffold", action="store_true", help="print the region a generated starter embeds")
    parser.add_argument(
        "--print-fonts",
        metavar="TARGET",
        choices=(*FONT_PREFIXES, "precache"),
        help="print the @font-face region / precache list one surface embeds",
    )
    parser.add_argument(
        "--sync-package-fonts",
        action="store_true",
        help="copy the faces the MV3 popup and the VS Code panel ship into their own package trees",
    )
    parser.add_argument(
        "--sync-surface-regions",
        action="store_true",
        help="rewrite the generated region inside every document that embeds one",
    )
    args = parser.parse_args()

    if args.print_surface:
        print(surface_block())
        return 0

    if args.print_scaffold:
        print(scaffold_block())
        return 0

    if args.print_fonts:
        print(precache_block() if args.print_fonts == "precache" else font_block(args.print_fonts))
        return 0

    if args.sync_package_fonts:
        changed = sync_package_fonts()
        print("copied " + ", ".join(changed) if changed else "package fonts already match web/public/fonts")
        return 0

    if args.sync_surface_regions:
        changed = sync_surface_regions()
        print("rewrote the region in " + ", ".join(changed) if changed else "every embedded region is current")
        return 0

    rendered = render()
    rendered_tailwind = render_tailwind()
    if args.check:
        stale = [
            str(path)
            for path, expected in ((OUTPUT, rendered), (OUTPUT_TAILWIND, rendered_tailwind))
            if (path.read_text(encoding="utf-8") if path.exists() else "") != expected
        ]
        stale += mirrored_font_drift()
        stale += region_drift()
        if stale:
            print(f"{', '.join(stale)} out of date — run python scripts/gen_theme_css.py", file=sys.stderr)
            return 1
        print("themes.css, tailwind-theme.css, every mirrored font and every embedded region match their sources")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    OUTPUT_TAILWIND.write_text(rendered_tailwind, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}\nwrote {OUTPUT_TAILWIND}")
    return 0


