"""Render the design token files into a static CSS custom-property sheet.

ThemeContext injects the same variables inline on <html>, but only after React mounts — every paint
before that (the HTML shell, the first committed frame) had nothing to resolve against and fell back
to literals scattered through the stylesheets. Those literals could only ever describe one theme, so
they were wrong for two of three, and wrong in the direction of a colour flash or an invisible
control. This sheet makes the first paint truthful; the inline injection still overrides it, because
inline styles beat any rule on the same element.

    python scripts/gen_theme_css.py            # rewrite web/src/styles/themes.css
    python scripts/gen_theme_css.py --check    # fail if the sheet is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

WEB = Path(__file__).resolve().parent.parent / "web"
DESIGN = WEB / "src" / "design"
OUTPUT = WEB / "src" / "styles" / "themes.css"

THEMES: tuple[tuple[str, str], ...] = (
    ("tokens.json", ':root,\n[data-theme="dark"]'),
    ("tokens.light.json", '[data-theme="light"]'),
    ("tokens.midnight.json", '[data-theme="midnight"]'),
)

_META_KEYS = frozenset({"$schema", "description", "version"})

SENTINEL_START = "/* design-tokens:start - generated by scripts/gen_theme_css.py --print-surface, do not edit */"
SENTINEL_END = "/* design-tokens:end */"

#: The dark tokens the offline surfaces embed, in declaration order.
SURFACE_TOKENS = (
    "--dt-colors-bg-primary",
    "--dt-colors-bg-secondary",
    "--dt-colors-border-default",
    "--dt-colors-border-focus",
    "--dt-colors-accent-default",
    "--dt-colors-text-primary",
    "--dt-colors-text-secondary",
    "--dt-colors-text-link",
    "--dt-colors-text-on-accent",
    "--dt-colors-status-success",
    "--dt-colors-status-error",
)


def token_lines(data: dict[str, Any]) -> list[tuple[str, str]]:
    """Flatten a token tree into ``--dt-`` declarations in file order."""
    out: list[tuple[str, str]] = []

    def walk(node: Any, prefix: list[str]) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                walk(value, [*prefix, key])
        elif prefix and prefix[0] not in _META_KEYS:
            out.append(("--dt-" + "-".join(prefix), str(node)))

    for group, values in data.items():
        if group in _META_KEYS:
            continue
        walk(values, [group])
    return out


def render() -> str:
    blocks: list[str] = [
        "/* Generated by scripts/gen_theme_css.py from web/src/design/tokens.*.json — do not edit by hand.",
        " * This is the pre-hydration paint. ThemeContext writes the same properties inline on <html>",
        " * once it mounts, and those inline values win, so user-chosen accents and live theme",
        " * switching are unaffected. Keep the token files as the only thing you edit.",
        " */",
        "",
    ]
    for name, selector in THEMES:
        data = json.loads((DESIGN / name).read_text(encoding="utf-8"))
        lines = token_lines(data)
        body = "\n".join(f"  {prop}: {value};" for prop, value in lines)
        blocks.append(f"/* {name} — {len(lines)} tokens */")
        blocks.append(f"{selector} {{\n{body}\n}}\n")
    return "\n".join(blocks)


def surface_block() -> str:
    """The dark tokens the two offline surfaces need, as one generated region.

    `raven/channels/webchat` and `extension/src/popup` are documents that never load the SPA bundle,
    so they cannot import themes.css. Left to hand-copy colours they drift into private palettes --
    the webchat page invented #8b5cf6 as its button surface and put white on it at 4.23:1. The region
    between the sentinels below is regenerated, and a gate compares it, so those surfaces keep one
    source of truth without needing a runtime file read.
    """
    values = dict(token_lines(json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))))
    missing = [name for name in SURFACE_TOKENS if name not in values]
    if missing:
        raise AssertionError(f"tokens.json publishes none of {missing}")
    body = "\n".join(f"  {name}: {values[name]};" for name in SURFACE_TOKENS)
    return f"{SENTINEL_START}\n{body}\n{SENTINEL_END}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the sheet is up to date")
    parser.add_argument("--print-surface", action="store_true", help="print the generated region the offline surfaces embed")
    args = parser.parse_args()

    if args.print_surface:
        print(surface_block())
        return 0

    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT} is out of date — run python scripts/gen_theme_css.py", file=sys.stderr)
            return 1
        print("themes.css matches the token files")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
